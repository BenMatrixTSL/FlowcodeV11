static int8_t MX_CDC_TransmitCplt_FS(MX_UINT8 *pbuf, MX_UINT32 *Len, MX_UINT8 epnum);

USBD_CDC_ItfTypeDef MX_USBD_Interface_fops_FS =
{
	MX_CDC_Init_FS,
	MX_CDC_DeInit_FS,
	MX_CDC_Control_FS,
	MX_CDC_Receive_FS,
	MX_CDC_TransmitCplt_FS
};

static int8_t MX_CDC_Init_FS(void)
{
	USBD_CDC_SetTxBuffer(&MX_USB_HANDLE_HUSBD, MX_USB_TxBuffer, 0);
	USBD_CDC_SetRxBuffer(&MX_USB_HANDLE_HUSBD, MX_USB_RxBuffer);

	MX_USBSer_RxByteCount = 0;
	MX_USBSer_RxPtr = 0;
	MX_USBSer_TxBusy = 0;

	return (USBD_OK);
}

static int8_t MX_CDC_DeInit_FS(void)
{
	return (USBD_OK);
}

static int8_t MX_CDC_Control_FS(MX_UINT8 cmd, MX_UINT8 *pbuf, MX_UINT16 length)
{
	//Line coding / control line requests are accepted but not acted upon -
	//Flowcode treats the link as a fixed configuration virtual COM port.
	return (USBD_OK);
}

static int8_t MX_CDC_Receive_FS(MX_UINT8 *Buf, MX_UINT32 *Len)
{
	//Called from USB interrupt context when a new packet of data has arrived.
	//Buf == MX_USB_RxBuffer, *Len == number of bytes received.

	MX_USBSer_RxByteCount = (MX_UINT8) (*Len);
	MX_USBSer_RxPtr = 0;

	//Re-arm reception for the next packet once this one has been drained
	USBD_CDC_SetRxBuffer(&MX_USB_HANDLE_HUSBD, MX_USB_RxBuffer);

	if (MX_USBSer_RxByteCount == 0)
		USBD_CDC_ReceivePacket(&MX_USB_HANDLE_HUSBD);

	return (USBD_OK);
}

static int8_t MX_CDC_TransmitCplt_FS(MX_UINT8 *Buf, MX_UINT32 *Len, MX_UINT8 epnum)
{
	MX_USBSer_TxBusy = 0;
	return (USBD_OK);
}

static MX_UINT8 MX_CDC_Transmit_FS(MX_UINT8 *Buf, MX_UINT16 Len)
{
	MX_UINT16 timeout = 0;
	USBD_CDC_HandleTypeDef *hcdc = (USBD_CDC_HandleTypeDef *)MX_USB_HANDLE_HUSBD.pClassData;

	if (MX_USB_HANDLE_HUSBD.dev_state != USBD_STATE_CONFIGURED)
		return (USBD_FAIL);

	//Wait for any previous packet to finish transmitting
	while ((hcdc->TxState != 0) && (timeout < 32000))
	{
		timeout = timeout + 1;
		delay_us(10);
	}

	if (hcdc->TxState != 0)
		return (USBD_BUSY);

	USBD_CDC_SetTxBuffer(&MX_USB_HANDLE_HUSBD, Buf, Len);
	return USBD_CDC_TransmitPacket(&MX_USB_HANDLE_HUSBD);
}


static MX_UINT8 MX_CDC_DrainRxByte(void)
{
	MX_UINT8 data;

	data = MX_USB_RxBuffer[MX_USBSer_RxPtr++];

	if (MX_USBSer_RxPtr >= MX_USBSer_RxByteCount)
	{
		MX_USBSer_RxPtr = 0;
		MX_USBSer_RxByteCount = 0;

		//Buffer has been fully drained - re-arm the endpoint for the next packet
		USBD_CDC_ReceivePacket(&MX_USB_HANDLE_HUSBD);
	}

	return data;
}


