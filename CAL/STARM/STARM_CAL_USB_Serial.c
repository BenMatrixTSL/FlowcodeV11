static void MX_USB_IntToUnicode(MX_UINT32 value, MX_UINT8 *pbuf, MX_UINT8 len)
{
	MX_UINT8 idx;

	for (idx = 0; idx < len; idx++)
	{
		if (((value >> 28)) < 0xA)
			pbuf[2 * idx] = (value >> 28) + '0';
		else
			pbuf[2 * idx] = (value >> 28) + 'A' - 10;

		value = value << 4;
		pbuf[2 * idx + 1] = 0;
	}
}


